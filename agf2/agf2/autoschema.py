class AutoSchemaState(BaseModel):
    info: ProjectInfo
    model: str
    headers: List[str]

    # Identified objects
    objects: List[str] = Field(default_factory=list)

    # Identified functions
    functions: List[str] = Field(default_factory=list)

    # Stubs (generated by worker_stub)
    stubs: Annotated[List[EndpointStub], add] = Field(default_factory=list)

    # Endpoints (generated by worker_endpoint)
    endpoints: Annotated[List[Endpoint], add] = Field(default_factory=list)


class WorkerStubState(BaseModel):
    info: ProjectInfo
    model: str
    objects: List[str]
    function: str


class WorkerEndpointUsageState(BaseModel):
    info: ProjectInfo
    model: str
    stub: EndpointStub
    type: Literal['function', 'construct', 'destruct']


def scan_objects_functions(state: AutoSchemaState):
    print(f"Identifying objects and functions in {state.headers}")
    res = run_scanner(state.info, state.model, state.headers)
    return {"objects": res['dedup_objects'], "functions": res['dedup_functions']}


def dispatch_worker_stub(state: AutoSchemaState):
    print(f"Dispatching workers")
    return [Send('worker_stub', WorkerStubState(
        info=state.info,
        model=state.model,
        objects=state.objects,
        function=func
    )) for func in state.functions]


def worker_stub(state: WorkerStubState):
    print(f'[*] Worker {state.function}')
    stubs = run_gen_stub(state.info, state.model, state.objects, state.function)
    if stubs is None:
        print(f'[{Colors.RED}STUB{Colors.END}] Failed to generate stubs for {state.function}')
        return {}
    else:
        print(f'[{Colors.GREEN}STUB{Colors.END}] Generated {len(stubs)} stubs for {state.function}')
        return {"stubs": stubs}


def post_worker_stub(state: AutoSchemaState):
    print(f"Post-processing stubs")
    print(state.stubs)
    return {}


def dispatch_worker_usage_endpoint(state: AutoSchemaState):
    print(f"Dispatching worker usage")
    tasks = []
    
    # Endpoint usage for each function
    tasks += [Send('worker_endpoint_usage', WorkerEndpointUsageState(
        info=state.info,
        model=state.model,
        stub=stub,
        type='function',
    )) for stub in state.stubs]

    # Object constructors
    tasks += [Send('worker_endpoint_usage', WorkerEndpointUsageState(
        info=state.info,
        model=state.model,
        stub=EndpointStub(endpoint_name=f'new {obj}', function_name=f'new_{obj}', variables=[
            Variable(name='object', typ=obj, dir='new')
        ]),
        type='construct',
    )) for obj in state.objects]

    # Object destructors
    tasks += [Send('worker_endpoint_usage', WorkerEndpointUsageState(
        info=state.info,
        model=state.model,
        stub=EndpointStub(endpoint_name=f'delete {obj}', function_name=f'delete_{obj}', variables=[
            Variable(name='object', typ=obj, dir='del')
        ]),
        type='destruct',
    )) for obj in state.objects]

    return tasks

def worker_endpoint_usage(state: WorkerEndpointUsageState):
    print(f'[*] Endpoint worker {state.stub.endpoint_name}')
    
    res = run_gen_endpoint(state.info, state.model, state.stub, state.type)
    if res is not None and isinstance(res.result, GenEndpointSuccess):
        print(f'[{Colors.GREEN}GEN{Colors.END}] {state.stub.endpoint_name}')
        return {"endpoints": [res.result.endpoint]}
    else:
        print(f'[{Colors.RED}GEN{Colors.END}] Failed to generate endpoint for {state.stub.endpoint_name}')
        return {}


def build():
    graph = StateGraph(AutoSchemaState)
    graph.add_node('scan_objects_functions', scan_objects_functions)

    graph.add_conditional_edges('scan_objects_functions', dispatch_worker_stub, {
        'worker_stub': 'worker_stub'
    })
    graph.add_node('worker_stub', worker_stub)
    graph.add_edge('worker_stub', 'post_worker_stub')

    graph.add_node('post_worker_stub', post_worker_stub)
    graph.add_conditional_edges('post_worker_stub', dispatch_worker_usage_endpoint, {
        'worker_endpoint_usage': 'worker_endpoint_usage'
    })
    graph.add_node('worker_endpoint_usage', worker_endpoint_usage)
    graph.add_edge('worker_endpoint_usage', END)

    graph.add_edge(START, 'scan_objects_functions')

    return graph.compile()

def main(args):
    if args.cache:
        print(f'Using SQLite cache')
        cache = SQLiteCacheFixed(database_path=".cache.db")
        set_llm_cache(cache)

    graph = build()
    info = ProjectInfo.model_validate_json(open(args.info).read())
    state = AutoSchemaState(
        info=info,
        model=args.model,
        headers=args.headers,
    )
    load_global_rag(info.rag)
    result = graph.invoke(state.model_dump())
    print(result)
    if args.output:
        with open(args.output, 'w') as f:
            schema = Schema(endpoints=result['endpoints'])
            f.write(schema.model_dump_json(indent=2))

        print(f'Wrote schema to {args.output}')


def register(subparser):
    parser = subparser.add_parser("autoschema")
    parser.add_argument("--info", type=str, required=True)
    parser.add_argument("--model", type=str, required=True)
    parser.add_argument("--output", type=str)
    parser.add_argument("--headers", type=str, required=True, nargs='+')

    parser.add_argument("--cache", action="store_true", help="Enable caching")
    parser.set_defaults(func=main)
