from .utils.spec import Objects, Functions, DetailedStub, Stub, Endpoint, Schema, ObjectArg
from .utils.search import get_example_usage
from .utils.visualize import visualize_graph
from .utils.sqlitecache import SQLiteCacheFixed

from .agents.endpoint_usage import run_endpoint_usage, EndpointUsageSuccess
from .agents.scanner import run_scanner


class AutoSchemaState(BaseModel):
    build_script: str
    config: str
    codebase: str
    header: str

    # Generated:

    # Identified objects
    objects: List[str] = Field(default_factory=list)

    # Identified functions
    functions: List[str] = Field(default_factory=list)

    # Stubs (generated by worker_stub)
    stubs: Annotated[List[Stub], add] = Field(default_factory=list)

    # Endpoints (generated by worker_endpoint)
    endpoints: Annotated[List[Endpoint], add] = Field(default_factory=list)


class WorkerStubState(BaseModel):
    header: str
    objects: List[str]
    function: str


class WorkerEndpointUsageState(BaseModel):
    build_script: str
    config: str
    codebase: str
    header: str
    stub: Stub
    type: Literal['function', 'construct', 'destruct']


def identify_objects_functions(state: AutoSchemaState):
    print(f"Identifying objects and functions in {state.header}")
    res = run_scanner([state.header])
    return {"objects": res['dedup_objects'], "functions": res['dedup_functions']}

def post_identify(state: AutoSchemaState):
    print(f"Post-identifying objects in {state.header}")
    return {}

def dispatch_worker_stub(state: AutoSchemaState):
    print(f"Dispatching {state.header}")
    return [Send('worker_stub', WorkerStubState(
        header=state.header,
        objects=state.objects,
        function=func
    )) for func in state.functions]


PROMPT_STUB = '''Given the following code, list of available objects, and example usage of the function `{function}`, describe the function signature for `{function}`.

Iterate over each argument (and the return value) and describe each argument's:
- "name"
- "type" C/C++ type
- "base_type" the underlying object matching this type (must match an entry in the provided list of objects or "none" if none of the object types match)
- "dir" which can be either:
    - "new" if the argument is being created (i.e. an output of the function)
    - "del" if the argument is being destructed (use the name of the function and docs to understand if this is the case) -- e.g. functions with words like "free" or "delete"
    - "*" in all other cases
- "is_optional" true if the argument can be null, false otherwise'''

def worker_stub(state: WorkerStubState):
    print(f'[*] Worker {state.function} in {state.header}')
    llm = ChatOpenAI(model="gpt-4o-mini").with_structured_output(DetailedStub)
    code = open(state.header, 'rb').read().decode('latin-1')
    example_usage = get_example_usage(state.header, state.function)
    stub: DetailedStub = llm.invoke(
        [
            {"role": "system", "content": PROMPT_STUB.format(function=state.function)},
            # {"role": "user", "content": f"// code:\n{code}"},
            {"role": "user", "content": f"// objects:\n{state.objects}"},
            {"role": "user", "content": f"// example usage:\n{example_usage}"}
        ]
    )
    stub.fixup(state.objects)
    stubs = stub.expand_stubs(state.function).stubs
    return {"stubs": stubs}


def post_worker_stub(state: AutoSchemaState):
    print(f"Post-processing stubs in {state.header}")
    print(state.stubs)
    return {}


def dispatch_worker_usage_endpoint(state: AutoSchemaState):
    print(f"Dispatching {state.header}")
    tasks = []
    
    # Endpoint usage for each function
    tasks += [Send('worker_endpoint_usage', WorkerEndpointUsageState(
        build_script=state.build_script,
        config=state.config,
        codebase=state.codebase,
        header=state.header,
        stub=stub,
        type='function',
    )) for stub in state.stubs]

    # Object constructors
    tasks += [Send('worker_endpoint_usage', WorkerEndpointUsageState(
        build_script=state.build_script,
        config=state.config,
        codebase=state.codebase,
        header=state.header,
        stub=Stub(function=f'new {obj}', object_args=[
            ObjectArg(name='object', typ=obj, dir='new')
        ]),
        type='construct',
    )) for obj in state.objects]

    # Object destructors
    tasks += [Send('worker_endpoint_usage', WorkerEndpointUsageState(
        build_script=state.build_script,
        config=state.config,
        codebase=state.codebase,
        header=state.header,
        stub=Stub(function=f'delete {obj}', object_args=[
            ObjectArg(name='object', typ=obj, dir='del')
        ]),
        type='destruct',
    )) for obj in state.objects]

    return tasks

def worker_endpoint_usage(state: WorkerEndpointUsageState):
    print(f'[*] Endpoint worker {state.stub.function} in {state.header}')
    
    res = run_endpoint_usage(state.build_script, state.config, state.codebase, state.header, state.stub, state.type)
    if isinstance(res.result, EndpointUsageSuccess):
        print(f'Successfully generated endpoint for {state.stub.function}')
        return {"endpoints": [res.result.endpoint]}
    else:
        print(f'Failed to generate endpoint for {state.stub.function}')
        return {}


def build():
    graph = StateGraph(AutoSchemaState)
    graph.add_node('identify_objects_functions', identify_objects_functions)
    graph.add_edge('identify_objects_functions', 'post_identify')

    graph.add_node('post_identify', post_identify)
    graph.add_conditional_edges('post_identify', dispatch_worker_stub, {
        'worker_stub': 'worker_stub'
    })
    graph.add_node('worker_stub', worker_stub)
    graph.add_edge('worker_stub', 'post_worker_stub')

    graph.add_node('post_worker_stub', post_worker_stub)
    graph.add_conditional_edges('post_worker_stub', dispatch_worker_usage_endpoint, {
        'worker_endpoint_usage': 'worker_endpoint_usage'
    })
    graph.add_node('worker_endpoint_usage', worker_endpoint_usage)
    graph.add_edge('worker_endpoint_usage', END)

    graph.add_edge(START, 'identify_objects_functions')

    return graph.compile()

def main(args):
    if args.cache:
        print(f'Using SQLite cache')
        cache = SQLiteCacheFixed(database_path=".cache.db")
        set_llm_cache(cache)

    graph = build()
    if args.visualize:
        visualize_graph(graph)
    else:
        state = AutoSchemaState(
            build_script=args.build_script,
            config=args.config,
            codebase=args.codebase,
            header=args.header,
        )
        result = graph.invoke(state.model_dump())
        print(result)
        if args.output:
            with open(args.output, 'w') as f:
                schema = Schema(endpoints=result['endpoints'])
                f.write(schema.model_dump_json(indent=2))

            print(f'Wrote schema to {args.output}')


def register(subparser):
    parser = subparser.add_parser("autoschema")
    parser.add_argument("--build-script", type=str, required=True)
    parser.add_argument("--config", type=str, required=True)
    parser.add_argument("--codebase", type=str, required=True)
    parser.add_argument("--header", type=str, required=True)

    parser.add_argument("--output", type=str)

    parser.add_argument("--cache", action="store_true", help="Enable caching")

    parser.add_argument("--visualize", action="store_true", help="Display graph visualization in a window")
    parser.set_defaults(func=main)
